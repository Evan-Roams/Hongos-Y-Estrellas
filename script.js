function render() {
  const s = scenes[index];

  els.current.textContent = index + 1;
  els.leftNumber.textContent = index * 2 + 1;
  els.rightNumber.textContent = index * 2 + 2;

  if (isMobile()) {
    // MOBILE:
    // One complete scene per physical page.
    els.mobileChapter.textContent = s.chapter;

    // Only the first scene uses the name of the story.
    els.mobileTitle.textContent =
      index === 0 ? "Hongos y Estrellas" : s.title;

    // The complete content of the scene.
    els.rightText.textContent =
      `${s.left}\n\n${s.right}`;

  } else {
    // DESKTOP:
    // Keep the two-page spread.
    els.chapter.textContent = s.chapter;
    els.title.textContent = s.title;
    els.leftText.textContent = s.left;
    els.rightText.textContent = s.right;
  }

  setBackground(s.bg);
}

function go(direction) {
  if (locked) return;

  const next = index + direction;

  if (next < 0 || next >= scenes.length) {
    return;
  }

  locked = true;

  const mobile = isMobile();

  if (!mobile) {
    els.turn.classList.remove("animating");
    void els.turn.offsetWidth;
    els.turn.classList.add("animating");
  }

  setTimeout(() => {
    index = next;
    render();
  }, mobile ? 80 : 380);

  setTimeout(() => {
    els.turn.classList.remove("animating");
    locked = false;
  }, mobile ? 180 : 850);
}

